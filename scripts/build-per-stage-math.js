/**
 * Read a backend-stage-*.csv (single multi-question file, or a merged file like
 * backend-stage-MERGED-2026-05-22T14-32-07.csv) and emit a **per-question
 * walkthrough** showing the literal subtraction math behind every delta.
 *
 * Output format (CSV, tab-friendly — opens cleanly in Excel/Sheets):
 *
 *   Q01    What is the difference between unit, integration, and end-to-end tests?
 *   Answer length (chars)    2589
 *
 *   Stage    Finished at    Previous stage finished at    Math    Delta (ms)
 *   preDiscovery:start                13:19:21    -    (start of stopwatch)    0
 *   preDiscovery:canUserAccessRag     13:19:21    13:19:21    19:20.846 - 19:20.792    54
 *   …
 *   service:firstToken                13:19:32    13:19:28    19:32.162 - 19:28.421    3741
 *   TOTAL                                                     service:firstToken - preDiscovery:start    11370 ms
 *
 *   <blank row>
 *   <next question block>
 *
 * Stage order is **whatever the input gives us** — so new stages (e.g.
 * `preDiscovery:vectorSearch`, added on 2026-05-28) flow through with no
 * changes here.
 *
 * Usage:
 *   node scripts/build-per-stage-math.js <input.csv> [output.csv]
 *
 * If no output is given, writes alongside the input as
 *   <input-basename>-per-stage-math.csv
 *
 * Generated by Claude.
 */

const fs = require('fs')
const path = require('path')

// -------------------------------------------------------------------- args

const inputPath = process.argv[2]
if (!inputPath) {
  console.error('Usage: node scripts/build-per-stage-math.js <input.csv> [output.csv]')
  process.exit(1)
}
if (!fs.existsSync(inputPath)) {
  console.error(`Input not found: ${inputPath}`)
  process.exit(1)
}

const outputPath =
  process.argv[3] ||
  path.join(
    path.dirname(inputPath),
    path.basename(inputPath, path.extname(inputPath)) + '-per-stage-math.csv'
  )

// ------------------------------------------------------------------- parse

const raw = fs.readFileSync(inputPath, 'utf8').replace(/\r\n/g, '\n')

function parseCsvLine(line) {
  const out = []
  let cur = ''
  let inQuotes = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (inQuotes) {
      if (c === '"' && line[i + 1] === '"') {
        cur += '"'
        i++
      } else if (c === '"') {
        inQuotes = false
      } else {
        cur += c
      }
    } else {
      if (c === ',') {
        out.push(cur)
        cur = ''
      } else if (c === '"') {
        inQuotes = true
      } else {
        cur += c
      }
    }
  }
  out.push(cur)
  return out
}

function escapeCsv(v) {
  if (v === null || v === undefined) return ''
  const s = String(v)
  if (/[",\n\r]/.test(s)) return `"${s.replace(/"/g, '""')}"`
  return s
}

function parseTotalMs(s) {
  if (s == null) return null
  const m = String(s).match(/\d+/)
  if (!m) return null
  return parseInt(m[0], 10)
}

function parseDeltaMs(s) {
  if (s == null) return null
  const t = String(s).trim()
  if (t === '' || t === '-') return 0
  const m = t.match(/-?\d+/)
  if (!m) return null
  return parseInt(m[0], 10)
}

/**
 * Stage-name pattern. Matches `preDiscovery:canUserAccessRag`, the older
 * `preDiscovery:shouldRetrieve+getKeywords`, and the 2026-05-28 renamed
 * `discovery:canUserAccessRag + vectorSearchResult` (spaces + plus signs).
 */
const STAGE_KEY_RE = /^[a-zA-Z][a-zA-Z0-9]*(:[a-zA-Z0-9+ ]+)+$/

// Walk lines, build question blocks. Each block:
//   { question, answerLength, rows: [{stage, timestamp, deltaMs}], totalMs }
const blocks = []
let current = null

const lines = raw.split('\n')
for (let i = 0; i < lines.length; i++) {
  const fields = parseCsvLine(lines[i])
  const head = fields[0]

  if (head === 'User') {
    if (current) blocks.push(current)
    current = { question: '', answerLength: null, rows: [], totalMs: null }
    continue
  }
  if (head === 'Question') {
    if (current) current.question = fields[1] || ''
    continue
  }
  if (head === 'Answer Length') {
    if (current) current.answerLength = parseInt(fields[1], 10)
    continue
  }
  if (current && head && STAGE_KEY_RE.test(head)) {
    current.rows.push({
      stage: head,
      timestamp: fields[1] || '',
      deltaMs: parseDeltaMs(fields[2])
    })
    continue
  }
  if (current && head === 'Total') {
    current.totalMs = parseTotalMs(fields[2] || fields[1] || '')
    continue
  }
}
if (current) blocks.push(current)

if (!blocks.length) {
  console.error('No question blocks found in input. Expected lines starting with User,/Question,.')
  process.exit(1)
}

// ----------------------------------------------------------- format helpers

/**
 * "13:19:20.792" → "13:19:21" (matches Excel's H:MM:SS formatting — rounds
 *                                to nearest second).
 */
function roundToSec(ts) {
  if (!ts) return ''
  const m = ts.match(/^(\d{1,2}):(\d{2}):(\d{2})(?:\.(\d+))?$/)
  if (!m) return ts
  const h = m[1].padStart(2, '0')
  const min = m[2]
  const secWhole = parseInt(m[3], 10)
  const frac = m[4] ? parseFloat('0.' + m[4]) : 0
  let rounded = secWhole + (frac >= 0.5 ? 1 : 0)
  let minNum = parseInt(min, 10)
  let hNum = parseInt(h, 10)
  if (rounded === 60) {
    rounded = 0
    minNum += 1
    if (minNum === 60) {
      minNum = 0
      hNum = (hNum + 1) % 24
    }
  }
  return [
    String(hNum).padStart(2, '0'),
    String(minNum).padStart(2, '0'),
    String(rounded).padStart(2, '0')
  ].join(':')
}

/**
 * "13:19:20.792" → "19:20.792" (drop the hour for the Math column).
 */
function mmSsFff(ts) {
  if (!ts) return ''
  const m = ts.match(/^(\d{1,2}):(\d{2}:\d{2}(?:\.\d+)?)$/)
  if (!m) return ts
  return m[2]
}

// --------------------------------------------------------------- render

const HEADER = ['Stage', 'Finished at', 'Previous stage finished at', 'Math', 'Delta (ms)']

const csvLines = []

/**
 * "13:19:20.792" → ms since midnight (for sorting & delta math).
 */
function tsToMs(ts) {
  const m = String(ts || '').match(/^(\d{1,2}):(\d{2}):(\d{2})(?:\.(\d+))?$/)
  if (!m) return null
  const h = parseInt(m[1], 10)
  const min = parseInt(m[2], 10)
  const sec = parseInt(m[3], 10)
  const frac = m[4] ? parseInt(m[4].padEnd(3, '0').slice(0, 3), 10) : 0
  return h * 3600000 + min * 60000 + sec * 1000 + frac
}

blocks.forEach((b, idx) => {
  const qLabel = 'Q' + String(idx + 1).padStart(2, '0')

  // Question + answer length, blank, then the stage table.
  csvLines.push([qLabel, b.question].map(escapeCsv).join(','))
  csvLines.push(
    ['Answer length (chars)', b.answerLength == null ? '' : String(b.answerLength)]
      .map(escapeCsv)
      .join(',')
  )
  csvLines.push('') // blank row
  csvLines.push(HEADER.map(escapeCsv).join(','))

  // Sort rows by wall-clock timestamp so deltas reflect actual time elapsed.
  // Some new stages (e.g. preDiscovery:vectorSearch) finish out of pipeline
  // order — without this sort, deltas can come out negative.
  const sortedRows = b.rows
    .map((r) => ({ ...r, _tsMs: tsToMs(r.timestamp) }))
    .filter((r) => r._tsMs != null)
    .sort((a, c) => a._tsMs - c._tsMs)

  let prev = null
  for (const r of sortedRows) {
    const tsShort = roundToSec(r.timestamp)
    let prevShort = '-'
    let math = '(start of stopwatch)'
    let delta = 0
    if (prev) {
      prevShort = roundToSec(prev.timestamp)
      math = `${mmSsFff(r.timestamp)} - ${mmSsFff(prev.timestamp)}`
      // Compute delta from timestamps directly (don't trust DOM's DELTA
      // value if rows were re-sorted from DOM order).
      delta = r._tsMs - prev._tsMs
    }
    csvLines.push(
      [r.stage, tsShort, prevShort, math, String(delta)].map(escapeCsv).join(',')
    )
    prev = r
  }

  // TOTAL row
  csvLines.push(
    [
      'TOTAL',
      '',
      '',
      'service:firstToken - preDiscovery:start',
      b.totalMs == null ? '' : `${b.totalMs} ms`
    ]
      .map(escapeCsv)
      .join(',')
  )

  // Blank separator between question blocks (skip after last).
  if (idx < blocks.length - 1) {
    csvLines.push('')
    csvLines.push('')
  }
})

fs.writeFileSync(outputPath, csvLines.join('\n') + '\n', 'utf8')

console.log(`Questions parsed: ${blocks.length}`)
console.log(`CSV written: ${outputPath}`)
